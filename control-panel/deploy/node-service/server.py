# ── Background start state ──────────────────────────────────────────────
_start_lock = threading.Lock()
_start_in_progress = False
_start_progress = {"status": "idle", "message": "", "error": None}


class ArgsNamespace:
    def __init__(self, **kwargs):
        for k, v in kwargs.items():
            setattr(self, k, v)


def _load_config() -> dict:
    """Load simplified config from config.json."""
    with open(SIMPLIFIED_CONFIG, "r", encoding="utf-8") as f:
        return json.load(f)


def _save_config(cfg: dict):
    """Save simplified config only. user_config.json will be generated by ctl.cmd_start."""
    with open(SIMPLIFIED_CONFIG, "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=4, ensure_ascii=False)


def _merge_config(cfg: dict, patch: dict):
    """Merge partial update into config (same semantics as PUT /vllm/config)."""
    for section, values in patch.items():
        if section in cfg and isinstance(values, dict) and isinstance(cfg[section], dict):
            cfg[section].update(values)
        elif section in cfg:
            cfg[section] = values


