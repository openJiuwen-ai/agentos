def _set_nested(d: dict, path: list, value):
    for key in path[:-1]:
        d = d.setdefault(key, {})
    d[path[-1]] = value


def _ensure_dirs():
    TEMPLATES_DIR.mkdir(parents=True, exist_ok=True)
    USER_TEMPLATES_DIR.mkdir(parents=True, exist_ok=True)
    USER_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    _migrate_old_templates()


def _simplified_to_params(cfg: dict) -> dict:
    """Convert simplified config to params dict for build_user_config."""
    model = cfg.get("model", {})
    deploy = cfg.get("deploy", {})
    parallel = cfg.get("parallel", {})
    inference = cfg.get("inference", {})
    fmt = cfg.get("format", {})
    ports = cfg.get("ports", {})
    params = {}
    if model.get("weight_path"):
        params["weight_path"] = model["weight_path"]
    if model.get("model_path"):
        params["model_path"] = model["model_path"]
    if model.get("model_name"):
        params["model_name"] = model["model_name"]
    if deploy.get("image"):
        params["image_name"] = deploy["image"]
    if deploy.get("npu_num"):
        params["npu_num"] = deploy["npu_num"]
    for key in ("tensor_parallel_size", "data_parallel_size", "gpu_memory_utilization",
                "enable_expert_parallel", "quantization"):
        val = parallel.get(key)
        if val is not None:
            params[key] = val
    for key in ("max_model_len", "max_num_batched_tokens", "max_num_seqs", "enforce_eager"):
        val = inference.get(key)
        if val is not None:
            params[{"max_model_len": "max-model-len", "max_num_batched_tokens": "max-num-batched-tokens",
                    "max_num_seqs": "max-num-seqs", "enforce_eager": "enforce-eager"}[key]] = val
    for key in ("tokenizer_mode", "tool_call_parser", "reasoning_parser", "trust_remote_code"):
        val = fmt.get(key)
        if val is not None:
            params[{"tokenizer_mode": "tokenizer-mode", "tool_call_parser": "tool-call-parser",
                    "reasoning_parser": "reasoning-parser", "trust_remote_code": "trust-remote-code"}[key]] = val
    for key in ("controller_port", "coordinator_infer_port", "coordinator_mgmt_port",
                "coordinator_obs_port", "node_manager_port", "base_port"):
        val = ports.get(key)
        if val is not None:
            params[key] = val
    return params


def _migrate_old_templates():
    """Migrate old single-file templates (*.json directly in templates/) to folder format."""
    try:
        hw = ctl.detect_hardware_type()
    except RuntimeError:
        hw = "800I_A3"
    npu_num = ctl.default_npu_num(hw)

    for f in sorted(TEMPLATES_DIR.glob("*.json")):
        try:
            with open(f, "r", encoding="utf-8") as fp:
                data = json.load(fp)
        except (json.JSONDecodeError, OSError):
            continue
        folder_name = f.stem
        folder = TEMPLATES_DIR / folder_name
        if folder.exists():
            f.unlink()
            continue
        folder.mkdir(parents=True, exist_ok=True)
        template_cfg = data.get("config", {})
        template_meta = {
            "description": data.get("description", ""),
            "source": "system",
            "config": template_cfg,
        }
        with open(folder / "template.json", "w", encoding="utf-8") as fp:
            json.dump(template_meta, fp, indent=4, ensure_ascii=False)
        params = _simplified_to_params(template_cfg)
        params = {k: v for k, v in params.items() if v is not None}
        try:
            user_cfg = ctl.build_user_config(params, hw, npu_num)
        except (KeyError, TypeError):
            user_cfg = ctl.build_user_config({}, hw, npu_num)
        with open(folder / "user_config.json", "w", encoding="utf-8") as fp:
            json.dump(user_cfg, fp, indent=4, ensure_ascii=False)
        f.unlink()
        logger.info("migrated old template: %s -> %s/", f.name, folder_name)


def _sync_user_config(cfg: dict):
    """Sync simplified config fields into active user_config.json."""
    if not ACTIVE_USER_CONFIG.exists():
        return
    try:
        with open(ACTIVE_USER_CONFIG, "r", encoding="utf-8") as f:
            uc = json.load(f)
    except (json.JSONDecodeError, OSError):
        return
    for flat_key, path in _USER_CONFIG_MAPPING.items():
        section, field = flat_key.split(".", 1)
        if section in cfg and isinstance(cfg[section], dict) and field in cfg[section]:
            _set_nested(uc, path, cfg[section][field])
    with open(ACTIVE_USER_CONFIG, "w", encoding="utf-8") as f:
        json.dump(uc, f, indent=4, ensure_ascii=False)


def _load_templates_from_dir(directory: Path, source: str) -> list[dict]:
    """Load all templates from subfolders in a directory."""
    templates = []
    if not directory.exists():
        return templates
    for folder in sorted(p for p in directory.iterdir() if p.is_dir()):
        meta_file = folder / "template.json"
        if not meta_file.exists():
            continue
        try:
            with open(meta_file, "r", encoding="utf-8") as fp:
                data = json.load(fp)
        except (json.JSONDecodeError, OSError):
            continue
        data["name"] = folder.name
        data["source"] = source
        templates.append(data)
    return templates


def _find_template(name: str) -> tuple[Path | None, str]:
    """Find a template folder by name. Returns (folder_path, source) or (None, '')."""
    user_folder = USER_TEMPLATES_DIR / name
    if user_folder.is_dir() and (user_folder / "template.json").exists():
        return user_folder, "user"
    sys_folder = TEMPLATES_DIR / name
    if sys_folder.is_dir() and (sys_folder / "template.json").exists():
        return sys_folder, "system"
    return None, ""


