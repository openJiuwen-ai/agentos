@vllm_router.put("/config", response_model=ApiResponse, summary="Update config")
async def update_config(body: dict, _user: TokenData = Depends(require_admin)):
    """
    Update config fields. Only send fields you want to change, e.g.:
    {
        "model": {"model_name": "new-name", "weight_path": "/data/weights"},
        "parallel": {"tensor_parallel_size": 8}
    }
    """
    cfg = _load_config()
    _merge_config(cfg, body)
    _save_config(cfg)
    _sync_user_config(cfg)
    return ApiResponse(success=True, message="配置已保存")


@vllm_router.post("/start", response_model=ApiResponse, summary="Start vLLM container")
async def start_container(body: dict = None, _user: TokenData = Depends(require_admin)):
    """Start vLLM container. Returns immediately (202).

    Optional body: partial config fields to merge before start, e.g.:
    {"model": {"model_name": "new"}, "parallel": {"tensor_parallel_size": 8}}
    """
    global _start_in_progress, _start_progress
    with _start_lock:
        if _start_in_progress:
            raise HTTPException(status_code=409, detail="启动操作正在进行中，请稍候")
        _start_in_progress = True

    # validate config after acquiring lock
    try:
        cfg = _load_config()
        if body:
            _merge_config(cfg, body)
            _save_config(cfg)
            _sync_user_config(cfg)

        model = cfg.get("model", {})
        if not model.get("weight_path") or not model.get("model_path") or not model.get("model_name"):
            raise ValueError("缺少必填字段: model.weight_path, model.model_path, model.model_name")
    except Exception as exc:
        _start_in_progress = False
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    _start_progress = {"status": "queued", "message": "Start request accepted", "error": None}
    t = threading.Thread(target=_start_in_background, daemon=True)
    t.start()
    return ApiResponse(success=True, message="启动请求已接受，请轮询 GET /inference/status 获取进度")


