@vllm_router.get("/status", summary="Get container status")
async def get_status(_user: TokenData = Depends(require_admin)):
    """Get current container and service status."""
    result = {
        "container": "not running",
        "engine": "unknown",
    }
    rc, out, _ = ctl.run_cmd(f"docker inspect -f '{{{{.State.Status}}}}' {ctl.CONTAINER_NAME}")
    if rc == 0:
        result["container"] = out
        rc2, _, _ = ctl.run_cmd(
            f"docker exec {ctl.CONTAINER_NAME} ps aux | grep -v grep | grep mindieservice_daemon > /dev/null"
        )
        if rc2 == 0:
            result["engine"] = "mindie_motor"
        else:
            rc3, _, _ = ctl.run_cmd(
                f"docker exec {ctl.CONTAINER_NAME} ps aux | grep -v grep | grep -E 'python|boot.sh' > /dev/null"
            )
            result["engine"] = "vllm" if rc3 == 0 else "not_detected"
        rc4, logs, _ = ctl.run_cmd(f"docker logs --tail 10 {ctl.CONTAINER_NAME}")
        if rc4 == 0:
            result["recent_logs"] = logs
    result["config"] = _load_config()
    if _start_in_progress:
        result["start_progress"] = _start_progress
    return result


@vllm_router.get("/health", summary="Health check")
async def health(_user: TokenData = Depends(require_admin)):
    """Check if container is running."""
    rc, out, _ = ctl.run_cmd(f"docker inspect -f '{{{{.State.Status}}}}' {ctl.CONTAINER_NAME}")
    running = rc == 0 and "running" in out
    return {"healthy": running, "container": ctl.CONTAINER_NAME}


@vllm_router.get("/logs", summary="Get container logs")
async def get_logs(lines: int = 50, _user: TokenData = Depends(require_admin)):
    """Get recent container logs."""
    rc, out, _ = ctl.run_cmd(f"docker logs --tail {lines} {ctl.CONTAINER_NAME}")
    if rc != 0:
        raise HTTPException(status_code=404, detail="容器未运行或日志不可用")
    return {"logs": out.splitlines()}


