@vllm_router.post("/templates", response_model=ApiResponse, summary="Save current config as template")
async def save_template(body: dict, _user: TokenData = Depends(require_admin)):
    """Save the current config + user_config as a named template folder.

    Body: {"name": "my-config", "description": "optional description"}
    """
    _ensure_dirs()

    template_name = (body.get("name") or "").strip()
    description = (body.get("description") or "").strip()

    if not template_name:
        raise HTTPException(status_code=400, detail="模板名称不能为空")
    if not _NAME_RE.match(template_name):
        raise HTTPException(status_code=400, detail="模板名称只能包含字母、数字、下划线和连字符")
    if len(template_name) > 100:
        raise HTTPException(status_code=400, detail="模板名称不能超过 100 个字符")

    # Check name conflict by folder name
    existing, _ = _find_template(template_name)
    if existing is not None:
        raise HTTPException(status_code=409, detail=f"模板名称已存在: {template_name}")

    cfg = _load_config()
    folder = USER_TEMPLATES_DIR / template_name
    folder.mkdir(parents=True, exist_ok=False)

    template_meta = {
        "description": description,
        "source": "user",
        "config": cfg,
    }
    with open(folder / "template.json", "w", encoding="utf-8") as f:
        json.dump(template_meta, f, indent=4, ensure_ascii=False)

    if ACTIVE_USER_CONFIG.exists():
        shutil.copy2(ACTIVE_USER_CONFIG, folder / "user_config.json")
    else:
        try:
            hw = ctl.detect_hardware_type()
        except RuntimeError:
            hw = "800I_A3"
        npu_num = ctl.default_npu_num(hw)
        params = _simplified_to_params(cfg)
        params = {k: v for k, v in params.items() if v is not None}
        try:
            user_cfg = ctl.build_user_config(params, hw, npu_num)
        except KeyError:
            user_cfg = ctl.build_user_config({}, hw, npu_num)
        with open(folder / "user_config.json", "w", encoding="utf-8") as f:
            json.dump(user_cfg, f, indent=4, ensure_ascii=False)

    return ApiResponse(success=True, message=f"模板已保存: {template_name}")


@vllm_router.delete("/templates/{name}", response_model=ApiResponse, summary="Delete user template")
async def delete_template(name: str, _user: TokenData = Depends(require_admin)):
    """Delete a user-created template. System presets cannot be deleted."""
    _ensure_dirs()

    folder, source = _find_template(name)
    if folder is None:
        raise HTTPException(status_code=404, detail=f"模板不存在: {name}")

    if source == "system":
        raise HTTPException(status_code=403, detail="系统预设模板不可删除")

    shutil.rmtree(folder)

    return ApiResponse(success=True, message=f"模板已删除: {name}")


@vllm_router.post("/config/apply-template", response_model=ApiResponse, summary="Apply a template")
async def apply_template(body: dict, _user: TokenData = Depends(require_admin)):
    """Apply a template: copy its user_config and simplified config to active config.

    Body: {"name": "template-name"}
    """
    _ensure_dirs()

    template_name = (body.get("name") or "").strip()
    if not template_name:
        raise HTTPException(status_code=400, detail="模板名称不能为空")

    folder, _ = _find_template(template_name)
    if folder is None:
        raise HTTPException(status_code=404, detail=f"模板不存在: {template_name}")

    template_src = folder / "user_config.json"
    if not template_src.exists():
        raise HTTPException(status_code=500, detail=f"模板缺少 user_config.json: {template_name}")

    shutil.copy2(template_src, ACTIVE_USER_CONFIG)

    with open(folder / "template.json", "r", encoding="utf-8") as f:
        meta = json.load(f)
    template_cfg = meta.get("config", {})
    _save_config(template_cfg)

